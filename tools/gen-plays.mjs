import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTENT, SESSION, planStroke, strokeLines } from './plan.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// writes only when run as `npm run plays` (tests/native.mjs imports dailyPlay alone)
const main = !!process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
const out = (name, lines) => { if (main) writeFileSync(join(root, 'tests', 'native', name), lines.join('\n') + '\n'); };

/** Plays a whole round on a session as the game would, returning the script lines of the human's strokes. */
export function playRound(holes, { players = ['you'], seed, challenge = null, opts = {} } = {}) {
  const sess = SESSION.newSession({ seed, holes, players, mode: 'x', challenge });
  const lines = [];
  let guard = 0;
  while (!sess.finished && guard++ < 40) {
    const st = sess.state;
    const me = st.players[st.currentPlayer];
    if (me.id !== 'you') { SESSION.applyCommand(sess, SESSION.aiStrike(sess, me.id)); continue; }
    const course = sess.holes[sess.holeIndex];
    const plan = planStroke(st, course, opts);
    // the round's first stroke waits out the start countdown (0.9 s)
    if (!lines.length) lines.push('frames 60');
    lines.push(...strokeLines(plan.steps));
    const res = SESSION.applyCommand(sess, { type: 'strike', angle: plan.aim.angle, power: plan.aim.power, by: 'you' });
    if (res.error) throw new Error(res.error);
  }
  return { lines, sess };
}
