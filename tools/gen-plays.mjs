/** Today's daily course (by UTC date), planned and holed. */
export function dailyPlay(nowMs) {
  const course = CONTENT.dailyCourse(nowMs);
  const r = playRound([course], { seed: CONTENT.dailySeed(nowMs) });
  return [...header([`The daily for ${new Date(nowMs).toISOString().slice(0, 10)} (${CONTENT.dailySeed(nowMs)}), planned and holed.`]),
    ...start, 'click =Daily Challenge. One shared course per UTC day', `until 60 ${CONTENT.dailySeed(nowMs)}`, 'frames 10', 'click =Start',
    'until 120 Aim and strike', ...r.lines, 'until 900 =Results', 'frames 10', `expect — ${r.sess.result.results[0].total} vs par 4`, 'click Main menu', 'until 60 continue Journey'];
}

